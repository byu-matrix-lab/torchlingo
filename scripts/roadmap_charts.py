"""Generate the two Mermaid charts on the CS 479 Assignments page from the roadmap.

The Learning Suite "Assignments" page carries two pictures: the assignment roadmap, how each
assignment builds on the ones before, and the tutorial map, which tutorial prepares which
assignment. Until 2026-10-26 the Cowork session hand-wrote both as Mermaid, copying facts from
``roadmap.yaml`` and from each notebook's ``leads_to``, and they drifted as soon as either
changed: the tutorial map showed arrows no notebook's metadata had.

So the facts now live where the rest of the course's do. ``roadmap.yaml`` gives each
assignment a ``group`` (its colour) and holds a ``charts`` section with the assignment edges,
their labels and the tutorial arrows' labels; which arrows a tutorial has is still its own
``leads_to``. This module turns them into ``.mmd`` files under ``notes/roadmap/generated/``,
and ``render_roadmap.py`` writes and checks them with the roadmap, so CI fails on a stale chart
just as it does on a stale table.

What stays by hand is rendering: Cowork runs ``mmdc`` on the generated file and puts the
image on the page, since nothing here can write Learning Suite. The colours and the Mermaid
configuration are kept as they were, so a picture changes only when a fact does.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

import render_roadmap as rr

GENERATED = rr.SOURCE / "generated"
CONFIG_NAME = "assignment-roadmap.mermaid-config.json"

# Carried over from the hand-kept charts unchanged, so regenerating them changes no colour.
CLASSDEFS = {
    "spine": "fill:#dbeafe,stroke:#1d4ed8,stroke-width:2px,color:#0f172a",
    "eval": "fill:#dcfce7,stroke:#15803d,stroke-width:1.5px,color:#0f172a",
    "llm": "fill:#fef3c7,stroke:#b45309,stroke-width:1.5px,color:#0f172a",
    "early": "fill:#f1f5f9,stroke:#64748b,stroke-width:1px,color:#0f172a",
    "fp": "fill:#ede9fe,stroke:#6d28d9,stroke-width:2.5px,color:#0f172a",
    "tut": "fill:#f8fafc,stroke:#64748b,stroke-width:1px,color:#0f172a",
}
GROUPS = ("early", "spine", "eval", "llm")
# The order the hand-kept files declared and applied the classes in.
CLASS_ORDER = ("spine", "eval", "llm", "early", "fp")

MERMAID_CONFIG = {
    "theme": "default",
    "flowchart": {
        "htmlLabels": True,
        "curve": "basis",
        "nodeSpacing": 28,
        "rankSpacing": 46,
    },
    "themeVariables": {
        "fontFamily": "Helvetica, Arial, sans-serif",
        "fontSize": "15px",
    },
}

FP = "FP"
TUTORIAL_TITLE = re.compile(r"^# Tutorial (\d+): (.+)$")

HEADER = "%% GENERATED by scripts/render_roadmap.py from notes/roadmap/roadmap.yaml: edit there."
RENDER = "%% Render: mmdc -i {name}.mmd -o {name}.svg -c " + CONFIG_NAME + " -b white"


def _error(message: str) -> rr.RoadmapError:
    return rr.RoadmapError(f"{rr.DATA}: {message}")


def _bold(label: str) -> str:
    """The schedule's ``**A4** Title`` as Mermaid's ``<b>A4</b> Title``."""
    text = re.sub(r"\*\*(.+?)\*\*", r"<b>\1</b>", label)
    if '"' in text:
        raise _error(f"a chart label cannot hold a double quote: {label!r}")
    return text


def _edge_label(text: str) -> str:
    if "|" in text or '"' in text:
        raise _error(f"an arrow label cannot hold | or a double quote: {text!r}")
    return text


def _nodes(doc: dict) -> dict[str, dict]:
    """Every node the assignment charts may draw: grouped assignments, then FP."""
    nodes = {}
    for entry in doc.get("assignments", []):
        group = entry.get("group")
        if group is None or entry.get("dropped"):
            continue
        if group not in GROUPS:
            raise _error(f"{entry.get('id')} has group {group!r}; known are {GROUPS}")
        nodes[entry["id"]] = {"label": _bold(entry["label"]), "group": group}
    fp = doc.get("charts", {}).get("final_project")
    if not fp:
        raise _error("charts has no final_project")
    nodes[FP] = {
        "label": f"<b>{fp['label']}</b>",
        "note": fp.get("note"),
        "group": "fp",
    }
    return nodes


def _edges(doc: dict, nodes: dict[str, dict]) -> list[dict]:
    edges = doc.get("charts", {}).get("assignment_edges") or []
    for edge in edges:
        for end in ("from", "to"):
            if edge.get(end) not in nodes:
                raise _error(
                    f"an assignment edge's {end} is {edge.get(end)!r}, which is not a "
                    "grouped assignment or FP"
                )
        _edge_label(edge.get("carries", ""))
    return edges


def assignment_roadmap(doc: dict, here: str | None = None, name: str = "") -> str:
    """The assignment roadmap, or with ``here``, its deck-slide variant.

    Args:
        doc (dict): The parsed data file.
        here (str | None): An assignment to mark "you are here". Its presence also leaves out
            the early assignments with no arrow, which on a slide are only clutter.
        name (str): The file's stem, for the render line in its header.

    Returns:
        str: The Mermaid source.

    Raises:
        RoadmapError: If an edge names something not on the chart, or ``here`` does.
    """
    nodes = _nodes(doc)
    edges = _edges(doc, nodes)
    connected = {e["from"] for e in edges} | {e["to"] for e in edges}
    if here is not None and here not in nodes:
        raise _error(f"a slide's here is {here!r}, which is not on the chart")
    shown = [
        n
        for n, node in nodes.items()
        if not (here and node["group"] == "early" and n not in connected)
    ]

    def declare(n: str) -> str:
        label = nodes[n]["label"]
        if nodes[n].get("note"):
            label += f"<br/><small>{nodes[n]['note']}</small>"
        if n == here:
            label += "<br/><small><b>you are here</b></small>"
        return f'    {n}["{label}"]'

    def group(*names: str) -> list[str]:
        return [n for n in shown if nodes[n]["group"] in names]

    title = (
        f"%% The assignment roadmap for a deck slide, {here} marked; early assignments "
        "with no arrow left out."
        if here
        else "%% CS 479: how the assignments build on each other. Source of the image on "
        'the Learning Suite\n%% "Assignments" page (n2cK), which carries a WebP made from '
        "the SVG at 1.6x as a data URI."
    )
    render = RENDER.format(name=name)
    if here:
        render = render.replace(".svg", ".png") + " -w 900 -s 2.2"
    lines = [HEADER, title, render, "flowchart TB"]
    lines += [f"    classDef {g} {CLASSDEFS[g]}" for g in CLASS_ORDER]
    for block in (group("early"), group("spine", "fp"), group("eval", "llm")):
        if block:
            lines += [""] + [declare(n) for n in block]
    lines.append("")
    spine = group("spine")
    if not here and spine:
        lines += [
            f"    {n} ~~~ {spine[0]}" for n in group("early") if n not in connected
        ]
    for edge in edges:
        arrow = "-.->" if edge.get("prepares") else "-->"
        lines.append(f"    {edge['from']} {arrow}|{edge['carries']}| {edge['to']}")
    lines.append("")
    for g in CLASS_ORDER:
        members = group(g)
        if members:
            lines.append(f"    class {','.join(members)} {g}")
    if here:
        lines.append(f"    style {here} stroke-width:4px")
    return "\n".join(lines) + "\n"


def tutorial_map(doc: dict) -> str:
    """The tutorial map: each tutorial, top to bottom in number order, and its arrows.

    Arrows come from each tutorial's ``leads_to``; ``charts.tutorials`` labels them. The
    two must name the same targets, so a ``leads_to`` added to a notebook without a label,
    or a label left behind by one removed, fails the render rather than drawing a guess.

    Raises:
        RoadmapError: On a tutorial missing from ``charts.tutorials``, an entry with no
            tutorial, labels that disagree with ``leads_to``, or a title that cannot be read.
    """
    import notebook_meta as nm

    entries = doc.get("charts", {}).get("tutorials") or {}
    nodes = _nodes(doc)
    tutorials = sorted(
        p for p in nm.notebooks() if nm.read_meta(p)["family"] == "tutorial"
    )
    stems = {p.stem for p in tutorials}
    problems = [
        f"  {s}: a tutorial with no entry" for s in sorted(stems - set(entries))
    ]
    problems += [
        f"  {s}: an entry with no tutorial" for s in sorted(set(entries) - stems)
    ]

    declared, arrows, targets = [], [], []
    for path in tutorials:
        entry = entries.get(path.stem)
        if entry is None:
            continue
        notebook = json.loads(path.read_text(encoding="utf-8"))
        heading = "".join(notebook["cells"][0]["source"]).splitlines()[0]
        match = TUTORIAL_TITLE.match(heading)
        if not match:
            problems.append(
                f"  {path.stem}: first line {heading!r} is not '# Tutorial N: Title'"
            )
            continue
        number, title = match.groups()
        node = f"T{number}"
        declared.append(
            f'    {node}["<b>Tutorial {number}</b><br/>{entry.get("title", title)}"]'
        )
        leads_to = nm.read_meta(path).get("leads_to", [])
        labels = entry.get("labels") or {}
        if set(labels) != set(leads_to):
            problems.append(
                f"  {path.stem}: labels for {sorted(labels)}, but leads_to is {leads_to}"
            )
            continue
        after = entry.get("read_after")
        if after is not None:
            if after not in nodes:
                problems.append(
                    f"  {path.stem}: read_after {after!r} is not an assignment"
                )
                continue
            # Both heads, so Mermaid keeps the tutorial in its column; Cowork removes the
            # head at the assignment's end after rendering (the header says how).
            arrows.append(f"    {node} <-.->|read after {after}| {after}")
            targets.append(after)
        for target in leads_to:
            arrows.append(f"    {node} -->|{_edge_label(labels[target])}| {target}")
            targets.append(target)
    if problems:
        raise _error(
            "charts.tutorials and the tutorials disagree:\n" + "\n".join(problems)
        )

    shown = list(dict.fromkeys(targets))
    lines = [
        HEADER,
        (
            "%% CS 479: which TorchLingo tutorial prepares which assignment. Companion to "
            'assignment-roadmap.mmd,\n%% on the Learning Suite "Assignments" page (n2cK). '
            "Tutorials run top to bottom in number order."
        ),
        RENDER.format(name="tutorial-map"),
        (
            '%% A "read after" arrow is drawn <-.-> so the tutorial stays in the left '
            "column. After rendering,\n%% remove the marker-end from its path (L_T9_A14_0) "
            "so only the head at the tutorial shows,\n%% within that one <path> element: "
            "the SVG is one line, so a line-wide sed hits another edge."
        ),
        "flowchart LR",
    ]
    lines += [
        f"    classDef {g} {CLASSDEFS[g]}" for g in ("tut", "spine", "eval", "fp")
    ]
    lines += [""] + declared + [""]
    for n in shown:
        if n not in nodes:
            raise _error(f"the tutorial map names {n!r}, which is not on the chart")
        lines.append(f'    {n}["{nodes[n]["label"]}"]')
    lines += [""] + arrows + [""]
    lines.append(f"    class {','.join(d.split('[')[0].strip() for d in declared)} tut")
    for g in CLASS_ORDER:
        members = [n for n in shown if nodes[n]["group"] == g]
        if members:
            lines.append(f"    class {','.join(members)} {g}")
    return "\n".join(lines) + "\n"


def charts(doc: dict) -> dict[Path, str]:
    """Every generated chart file, path to contents.

    Args:
        doc (dict): The parsed data file.

    Returns:
        dict: Paths under ``GENERATED``, read at call time so a test can redirect it.
    """
    out = {
        GENERATED / "assignment-roadmap.mmd": assignment_roadmap(
            doc, name="assignment-roadmap"
        ),
        GENERATED / "tutorial-map.mmd": tutorial_map(doc),
        GENERATED / CONFIG_NAME: json.dumps(MERMAID_CONFIG, separators=(",", ":"))
        + "\n",
    }
    for slide in doc.get("charts", {}).get("slides") or []:
        out[GENERATED / f"{slide['name']}.mmd"] = assignment_roadmap(
            doc, here=slide["here"], name=slide["name"]
        )
    return out
